#include<stdio.h>
int main (void)
{
	const float  water_density = 1000.0;
	const float g = 9.8; // g - Gravity
	const float efficiency = 0.9;
	const float W2MW = 1000000.0; // Watts per MegaWATT 
	
	float height,flowrate,mass,work,power,pMW;
	//pMW - Power in MegaWatt
	
	//inputs
	printf("Enter the height of the dam :");
	scanf("%f",&height);

	printf("Enter the flowrate of water :");
	scanf("%f",&flowrate);

	//calculations
	mass = water_density * flowrate;

	work = mass * g * height;

	power = efficiency * work;

	pMW = power / W2MW;

	//display result 
	printf("Predicted power generated by the hydroelectric dam : %f megawatts\n",pMW);

	return 0;
}
